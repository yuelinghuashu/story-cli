test("中英文文案键集合完全一致（防止 i18n 双侧漂移）", () => {
  const zh = getLocale("zh") as unknown as Record<string, unknown>
  const en = getLocale("en") as unknown as Record<string, unknown>
  const zhKeys = Object.keys(zh).sort()
  const enKeys = Object.keys(en).sort()
  assert.deepStrictEqual(zhKeys, enKeys, "zh 与 en 的文案键应完全一致")
})

test("新增文案的中英文本均非空且执行无误", () => {
  const zh = getLocale("zh")
  const en = getLocale("en")
  assert.ok(zh.skippedExport(3).length > 0)
  assert.ok(en.skippedExport(3).length > 0)
  assert.ok(zh.newMissingTitle.length > 0)
  assert.ok(en.newMissingTitle.length > 0)
  assert.ok(zh.newTypeInvalid(["original"], "invalid").length > 0)
  assert.ok(en.newTypeInvalid(["original"], "invalid").length > 0)
  assert.ok(zh.newCreated("01-测试", "original").includes("01-测试"))
  assert.ok(en.newCreated("01-Test", "original").includes("01-Test"))
  assert.ok(zh.epubLicenseOriginal.length > 0)
  assert.ok(en.epubLicenseOriginal.length > 0)
  assert.ok(zh.epubLicenseFanfic("原作", "作者").includes("原作"))
  assert.ok(en.epubLicenseFanfic("Work", "Author").includes("Work"))
})

test("英文 totalWordCountFormat 不包含中文字符", () => {
  const en = getLocale("en")
  assert.strictEqual(en.totalWordCountFormat.tenThousand(18000), "~18.0K words")
  assert.ok(!/[一-龥]/.test(en.totalWordCountFormat.tenThousand(18000)))
})
